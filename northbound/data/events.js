function hasFired(fired, id) {
  if (!fired) return false;
  if (Array.isArray(fired)) return fired.includes(id);
  if (fired instanceof Set) return fired.has(id);
  if (typeof fired === 'object') return Boolean(fired[id]);
  return false;
}

/**
 * Weighted pick over every event legal for the current game state.
 * Filters on mile window, biome, `once`, and the `requires` predicate.
 * Returns the event object, or null when nothing qualifies.
 */
export function rollEvent(g, rng) {
  const mile = Number(g?.mile) || 0;
  const biome = biomeAtMile(mile);
  const fired = g?.firedEvents ?? g?.stats?.firedEvents ?? null;
  const roll = typeof rng === 'function' ? rng : Math.random;

  const pool = [];
  let total = 0;
  for (const e of EVENTS) {
    if (mile < e.minMile || mile > e.maxMile) continue;
    if (e.biomes && !e.biomes.includes(biome)) continue;
    if (e.once && hasFired(fired, e.id)) continue;
    if (typeof e.requires === 'function') {
      let ok = false;
      try {
        ok = Boolean(e.requires(g));
      } catch {
        ok = false;
      }
      if (!ok) continue;
    }
    pool.push(e);
    total += e.weight;
  }
  if (!pool.length || total <= 0) return null;

  let r = roll() * total;
  for (const e of pool) {
    r -= e.weight;
    if (r <= 0) return e;
  }
  return pool[pool.length - 1];
}

/** True when the card needs the event screen to present options. */
export function isChoiceCard(event) {
  return Boolean(event && Array.isArray(event.choices) && event.choices.length > 0);
}

export const EVENTS_BY_ID = Object.fromEntries(EVENTS.map((e) => [e.id, e]));
